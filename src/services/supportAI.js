const db = require('../db');

let client = null;
function getClient() {
  if (client) return client;
  if (!process.env.ANTHROPIC_API_KEY) return null;
  const Anthropic = require('@anthropic-ai/sdk');
  client = new Anthropic();
  return client;
}
const MODEL = process.env.SUPPORT_MODEL || 'claude-opus-4-8';

