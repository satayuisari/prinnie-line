// ข้อความเรื่องสลิป — ใช้ทั้งตอนลูกค้าพิมพ์ "โอนแล้ว" และตอนเตือนออเดอร์ค้าง
//
// bon 17 ก.ย. 69: "ผมไม่เห็นสลิป ให้บอทฉลาด ๆ บอกให้ส่งใหม่หรืออะไรที่เหมาะสม"
// เดิม: ลูกค้าพิมพ์ "โอนแล้ว" แต่ยังไม่เป็นสมาชิก → บอทเงียบ ลูกค้ารอเก้อ แอดมินก็ไม่เห็นสลิป
// ตอนนี้: ตอบตามสถานะจริงของออเดอร์ ไม่สัญญาว่าเงินเข้า ไม่เปิดสิทธิ์เอง
//
// เขียนตามกติกาใน CLAUDE.md: ไทยธรรมดา ประโยคสั้น บอกว่าต้องทำอะไรต่อชัด ๆ

const CLAIMS_PAID = /จ่ายแล้ว|จ่ายเงินแล้ว|โอนแล้ว|โอนเงินแล้ว|ชำระแล้ว|ตัดเงิน|เงินออก|ส่งสลิป|สลิป/;

const claimsPaid = (text) => CLAIMS_PAID.test(String(text || ''));

const whatOf = (order) => (order && order.type === 'couple')
  ? `ปลดล็อกผลดวงคู่ (${order.amount / 100} บาท)`
  : `สมาชิก Prinnie333 (${order ? order.amount / 100 : 399} บาท)`;

// ลูกค้าบอกว่าโอนแล้ว แต่ระบบยังไม่เปิดใช้งาน
// order = ออเดอร์ PENDING ล่าสุดของคนนี้ (หรือ null)
function claimReply(order) {
  if (order && order.slip_message_id) {
    return [
      'ได้รับสลิปของคุณแล้วค่ะ 🙏',
      'ทีมงานกำลังตรวจสอบการโอน ไม่ต้องโอนซ้ำนะคะ',
      'ตรวจเสร็จแล้วจะแจ้งกลับในแชทนี้ค่ะ',
    ].join('\n');
  }
  const lines = [
    'ขอบคุณค่ะ 🙏 ตอนนี้ระบบยังไม่ได้รับรูปสลิปของคุณ',
    '',
    'รบกวนส่ง "รูปสลิปการโอน" มาในแชทนี้อีกครั้งนะคะ',
    '• แคปหน้าจอสลิปจากแอปธนาคาร ให้เห็นทั้งใบ และเห็น QR ชัด',
    '• ส่งเป็นรูปภาพ ไม่ต้องพิมพ์ยอด',
    '',
    'ระบบจะตรวจและเปิดใช้งานให้อัตโนมัติ ไม่ต้องโอนซ้ำค่ะ',
  ];
  // ไม่มีออเดอร์ = ส่งสลิปมาก็ผูกกับอะไรไม่ได้ ต้องกดสมัครก่อน
  if (!order) lines.push('', 'ถ้ายังไม่ได้กดสมัครในไลน์นี้ กดเมนู "สมัครสมาชิก" ก่อน แล้วค่อยส่งสลิปนะคะ');
  return lines.join('\n');
}

// เตือนออเดอร์ค้าง (ยังไม่มีสลิป) — ส่งครั้งเดียวต่อคน
// round = { round, cutoff } จาก pickAnnounce.nextRound() · ใส่เฉพาะออเดอร์สมาชิก
function reminderText({ name, order, payUrl, round }) {
  const hello = name ? `สวัสดีค่ะ คุณ ${String(name).trim()}` : 'สวัสดีค่ะ';
  const lines = [
    hello,
    `รายการ${whatOf(order)} ของคุณ ยังไม่ได้รับสลิปค่ะ`,
    '',
    '• ถ้าโอนแล้ว: ส่งรูปสลิปการโอนมาในแชทนี้ได้เลย ระบบจะเปิดใช้งานให้อัตโนมัติ ไม่ต้องโอนซ้ำค่ะ',
    `• ถ้ายังไม่ได้โอน: สแกนจ่ายได้ที่ลิงก์นี้ค่ะ\n👉 ${payUrl}`,
  ];
  if (round && (!order || order.type !== 'couple')) {
    lines.push('', `สมัครภายใน ${round.cutoff} มีสิทธิ์ลุ้นดูดวงกับอาจารย์ปรินนี่ฟรี รอบ ${round.round} ค่ะ`);
  }
  return lines.join('\n');
}

module.exports = { claimsPaid, claimReply, reminderText, CLAIMS_PAID };
